export type Locale = "zh" | "en";
export type FontSize = "sm" | "md" | "lg" | "xl";

export interface Prefs {
  locale: Locale;
  font: FontSize;
}

const PREF_KEY = "leo-tree-prefs-v1";
const FONT_SCALE: Record<FontSize, string> = {
  sm: "0.9",
  md: "1",
  lg: "1.14",
  xl: "1.28",
};

/**
 * Inline boot script for the document head: applies the saved font scale and
 * locale before hydration. Generated from the same constants as `applyPrefs`
 * so the two can never drift.
 */
export const PREFS_BOOT_JS =
  `try{var p=JSON.parse(localStorage.getItem(${JSON.stringify(PREF_KEY)})||'{}');` +
  `var s=${JSON.stringify(FONT_SCALE)};` +
  `if(p.font&&s[p.font])document.documentElement.style.setProperty('--leo-fs',s[p.font]);` +
  `if(p.locale==='en')document.documentElement.lang='en';}catch(e){}`;

export const defaultPrefs: Prefs = { locale: "zh", font: "md" };

export function loadPrefs(): Prefs {
  if (typeof window === "undefined") return defaultPrefs;
  try {
    const raw = JSON.parse(localStorage.getItem(PREF_KEY) || "{}") as Partial<Prefs>;
    const locale: Locale = raw.locale === "en" ? "en" : "zh";
    const font: FontSize = raw.font === "sm" || raw.font === "lg" || raw.font === "xl" ? raw.font : "md";
    return { locale, font };
  } catch {
    return defaultPrefs;
  }
}

export function applyPrefs(p: Prefs) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = p.locale === "en" ? "en" : "zh-CN";
  document.documentElement.style.setProperty("--leo-fs", FONT_SCALE[p.font]);
}

export function savePrefs(p: Prefs) {
  applyPrefs(p);
  if (typeof window !== "undefined") localStorage.setItem(PREF_KEY, JSON.stringify(p));
}

